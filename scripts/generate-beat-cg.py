#!/usr/bin/env python3
"""Generate one event CG per location beat, reusing the cast art studio client.

The café set lives in `generate-cast-art.py` (one CG per speaker). The other beats
happen somewhere else, so they get one location illustration each: the bookshop in
the morning and the food truck at lunch. Reuse the same light and palette so the
story still reads as one visual novel.

Usage:
    python3 scripts/generate-beat-cg.py
    python3 scripts/generate-beat-cg.py --only morning-shop --force
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = importlib.util.spec_from_file_location("castart", ROOT / "scripts" / "generate-cast-art.py")
castart = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(castart)

OUT = castart.OUT
SEED = 737373

SCAFFOLD = (
    "visual novel event CG, cinematic composition, character on the right third with "
    "warm negative space on the left, muted plum and gold palette, soft cel shading, "
    "clean lineart, detailed eyes, warm natural light, shallow depth of field, "
    "{cast}, {pose}, {setting}, "
    "no text, no watermark, adults, fully clothed, modest clothing, tasteful"
)

BEATS = {
    "morning-shop": {
        "cast": (
            "a woman in her early thirties with chestnut brown hair in a loose bun, "
            "warm amber eyes, round gold glasses, ink-stained fingers, cream knit cardigan "
            "over a burgundy blouse, beige trousers"
        ),
        "pose": "leaning on the bookshop counter with a teacup, soft knowing smile, head tilted",
        "setting": (
            "her second-hand bookshop at 09:10, tall shelves of old books, a ladder, "
            "morning light through the shop window, dust motes, a hand-written price card"
        ),
    },
    "truck-lunch": {
        "cast": (
            "two women: Mia, mid-twenties, auburn hair in a messy ponytail, green eyes, "
            "freckles, mustard yellow sweater under a white canvas apron, dark jeans; and "
            "Sophia, early thirties, warm brown skin, dark curls in a low bun, thin gold "
            "glasses, black turtleneck, a long charcoal coat"
        ),
        "pose": (
            "Mia leaning out of the food truck service window with a tray and a bright grin, "
            "Sophia standing at the counter with a small notebook and a dry half-smile"
        ),
        "setting": (
            "Mia's food truck at 12:40, golden-hour autumn light, warm string lights, "
            "steam from the window, a quiet city street"
        ),
    },
}


def write_prompts() -> None:
    lines = [
        "# Beat scene prompts",
        "",
        "Generated by `scripts/generate-beat-cg.py` against rin-studio / ComfyUI.",
        "One location CG per non-café beat; the café set is in `PROMPTS.md`.",
        "",
    ]
    for beat_id, config in BEATS.items():
        lines += [
            f"## {beat_id}",
            "",
            "- size: `portrait`",
            f"- seed: `{SEED}`",
            f"- file: `beat-{beat_id}.png`",
            "",
            "```text",
            SCAFFOLD.format(**config),
            "```",
            "",
        ]
    (OUT / "BEAT_PROMPTS.md").write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default=",".join(BEATS))
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--studio", default=castart.STUDIO)
    args = parser.parse_args()

    write_prompts()
    ids = [part.strip() for part in args.only.split(",") if part.strip()]
    for beat_id in ids:
        if beat_id not in BEATS:
            parser.error(f"unknown beat: {beat_id}")
        config = BEATS[beat_id]
        prompt = SCAFFOLD.format(**config)
        dest = OUT / f"beat-{beat_id}.png"
        if dest.exists() and not args.force:
            print(f"{beat_id}: exists, skipping (use --force)")
            continue
        print(f"{beat_id}:")
        result = castart.generate(prompt, "portrait", SEED, studio=args.studio)
        castart._download(f"{args.studio}{result['url']}", dest)
        web = castart.scene_web(dest)
        print(f"  -> {dest.relative_to(ROOT)}")
        print(f"  -> {web.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
