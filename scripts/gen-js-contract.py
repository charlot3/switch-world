#!/usr/bin/env python3
"""Generate ``web/js/vocab.js`` from ``switch_world/domain/protocol.py``.

The dashboard must not keep a second copy of the cast order, event kinds, take
boundaries or action/response modes.  Run this script after changing the Python
vocabulary; CI runs it with ``--check`` so a stale generated file fails the
build instead of drifting silently.

    python scripts/gen-js-contract.py
    python scripts/gen-js-contract.py --check
"""
from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web" / "js" / "vocab.js"

HEADER = """\
// Generated by scripts/gen-js-contract.py from switch_world/domain/protocol.py.
// Do not edit by hand. Run `python scripts/gen-js-contract.py` after changing
// the backend vocabulary; `python scripts/gen-js-contract.py --check` verifies
// the checked-in file is current.
"""


def _js_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _array(name: str, values: tuple[str, ...]) -> str:
    body = ", ".join(_js_string(value) for value in values)
    return f"export const {name} = Object.freeze([{body}]);\n"


def _set(name: str, values: tuple[str, ...]) -> str:
    body = ", ".join(_js_string(value) for value in values)
    return f"export const {name} = new Set([{body}]);\n"


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from switch_world.domain import protocol

    lines = [HEADER]
    lines.append(_array("CAST_ORDER", protocol.CAST_ORDER))
    lines.append("export const ORDER = CAST_ORDER;\n")
    lines.append(_set("SCENE_EVENT_KINDS", protocol.SCENE_EVENT_KINDS))
    lines.append(_set("SPEECH_MODES", protocol.SPEECH_MODES))
    lines.append(_set("TAKE_BOUNDARY_EVENT_KINDS", protocol.TAKE_BOUNDARY_EVENT_KINDS))
    lines.append(_set("TAKE_CHANGE_EVENT_KINDS", protocol.TAKE_CHANGE_EVENT_KINDS))
    lines.append(_set("ACTION_MODES", protocol.ACTION_MODES))
    lines.append(_set("RESPONSE_MODES", protocol.RESPONSE_MODES))
    lines.append(_array("EVENT_KINDS", protocol.EVENT_KINDS))
    lines.append(_array("TAKE_ORDER", protocol.TAKE_ORDER))
    lines.append(_array("CUE_OPS", protocol.CUE_OPS))
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if web/js/vocab.js does not match the generator",
    )
    args = parser.parse_args(argv)

    generated = render()
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"missing generated file: {OUTPUT}", file=sys.stderr)
            return 1
        if current == generated:
            print(f"{OUTPUT.relative_to(ROOT)} is current")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile="checked-in",
            tofile="generated",
        )
        sys.stderr.writelines(diff)
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
